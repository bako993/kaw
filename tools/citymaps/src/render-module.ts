import type { CityGround } from '@kaw/shared';

export function renderModule(ground: CityGround, exportName: string, sourcePath: string): string {
  return [
    `// Generated by tools/citymaps from ${sourcePath}. Do not edit by hand.`,
    `// Map data © OpenStreetMap contributors (ODbL).`,
    `import type { CityGround } from '@kaw/shared';`,
    '',
    `export const ${exportName}: CityGround = ${JSON.stringify(ground, null, 2)};`,
    '',
  ].join('\n');
}
