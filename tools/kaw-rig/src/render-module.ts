import type { KawRig } from './rig-types.ts';

export function renderModule(rig: KawRig, exportName: string, sourcePath: string): string {
  return [
    `// Generated by tools/kaw-rig from ${sourcePath}. Do not edit by hand.`,
    `import type { KawRig } from '../model/rig';`,
    '',
    `export const ${exportName}: KawRig = ${JSON.stringify(rig, null, 2)};`,
    '',
  ].join('\n');
}
